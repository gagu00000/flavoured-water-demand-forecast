// Copies the code shared with the notebook into the dashboard. Runs before dev/build.
//
// 1. The Python forecasting engine -> public/py, so the browser (Pyodide) runs
//    exactly the same code as the notebook. Only the modules the pipeline needs
//    are shipped: data.py (reads the 789 MB CSV) and llm_client.py (notebook-side
//    LLM calls) stay out of the browser.
// 2. The LLM system prompts (interpretation + chat) -> server/prompt.generated.ts, so the Netlify Function
//    sends exactly the same instructions as the notebook (functions cannot read
//    arbitrary files at runtime, so the text is bundled as a module).

import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const projectRoot = join(here, "..", "..");
const source = join(projectRoot, "forecasting_core");
const target = join(here, "..", "public", "py", "forecasting_core");

export const CORE_FILES = [
  "__init__.py",
  "series.py",
  "metrics.py",
  "features.py",
  "models.py",
  "backtest.py",
  "analysis.py",
  "pipeline.py",
  "fallback.py",
  "grounding.py",
];

rmSync(join(here, "..", "public", "py"), { recursive: true, force: true });
mkdirSync(target, { recursive: true });

const hash = createHash("sha256");
for (const file of CORE_FILES) {
  const text = readFileSync(join(source, file), "utf8");
  hash.update(file).update(text);
  writeFileSync(join(target, file), text);
}

const manifest = { package: "forecasting_core", files: CORE_FILES, hash: hash.digest("hex").slice(0, 12) };
writeFileSync(join(here, "..", "public", "py", "manifest.json"), JSON.stringify(manifest, null, 2));
console.log(`sync-shared: copied ${CORE_FILES.length} Python files (hash ${manifest.hash})`);

const prompt = readFileSync(join(projectRoot, "prompts", "interpretation_system.md"), "utf8");
const chatPrompt = readFileSync(join(projectRoot, "prompts", "chat_system.md"), "utf8");
mkdirSync(join(here, "..", "server"), { recursive: true });
writeFileSync(
  join(here, "..", "server", "prompt.generated.ts"),
  `// GENERATED by scripts/sync-shared.mjs from prompts/*.md - do not edit.
` +
    `export const SYSTEM_PROMPT = ${JSON.stringify(prompt)};
` +
    `export const CHAT_PROMPT = ${JSON.stringify(chatPrompt)};
`,
);
console.log("sync-shared: wrote server/prompt.generated.ts");
